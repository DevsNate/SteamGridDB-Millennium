// Copies the plugin's small runtime libraries into frontend/vendor/ so a bare
// `starlight pack` (no package install) can build the plugin. Run it after
// changing a dependency version: `pnpm install && node scripts/vendor.mjs`.
// tsconfig.json maps each package name to its folder here.
import { copyFile, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const vendor = join(root, 'frontend/vendor');
// pnpm links every direct dependency into the root node_modules.
const packageDir = (name) => join(root, 'node_modules', name);

// name, ESM or CJS, then [source, target] files. The license is copied too.
const packages = [
  ['async-wait-until', 'module', [['dist/index.esm.js', 'index.js'], ['dist/index.d.ts', 'index.d.ts']]],
  ['just-debounce', 'commonjs', [['index.js', 'index.js'], ['index.d.ts', 'index.d.ts']]],
  ['qrcode.react', 'module', [['lib/esm/index.js', 'index.js'], ['lib/index.d.ts', 'index.d.ts']]],
  ['react-fast-compare', 'commonjs', [['index.js', 'index.js'], ['index.d.ts', 'index.d.ts']]],
  ['react-string-replace', 'commonjs', [['index.js', 'index.js'], ['index.d.ts', 'index.d.ts']]],
];

const licenseOf = async (dir, meta) => {
  for (const name of await readdir(dir)) {
    if (/^licen[cs]e(\.md|\.txt)?$/i.test(name)) return readFile(join(dir, name), 'utf8');
  }
  // async-wait-until ships no license file; its package.json says MIT.
  if (meta.license !== 'MIT') throw new Error(`${meta.name}: no license file`);
  const author = typeof meta.author === 'string' ? meta.author : meta.author?.name;
  return `MIT License\n\nCopyright (c) ${author}\n\n${MIT_BODY}`;
};

