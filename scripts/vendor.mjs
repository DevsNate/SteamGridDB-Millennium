await rm(vendor, { recursive: true, force: true });
const readme = ['# Vendored libraries', '', 'Generated by `scripts/vendor.mjs`; do not edit by hand.', '', '| Package | Version | License | Source |', '|---|---|---|---|'];

for (const [name, type, files] of packages) {
  const dir = packageDir(name);
  const meta = JSON.parse(await readFile(join(dir, 'package.json'), 'utf8'));
  const target = join(vendor, name);
  await mkdir(target, { recursive: true });
  for (const [from, to] of files) await copyFile(join(dir, from), join(target, to));
  await writeFile(join(target, 'LICENSE'), await licenseOf(dir, meta));
  await writeFile(join(target, 'package.json'), `${JSON.stringify({
    name, version: meta.version, license: meta.license, type, main: 'index.js', types: 'index.d.ts',
  }, null, 2)}\n`);
  const repo = String(meta.repository?.url ?? meta.repository ?? '').replace(/^git\+|\.git$/g, '').replace(/^git:/, 'https:');
  readme.push(`| \`${name}\` | ${meta.version} | ${meta.license} | ${repo.includes('://') ? repo : `https://github.com/${repo}`} |`);
}

// react-icons: only the icons the plugin imports, rendered by a small IconBase.
const iconsDir = packageDir('react-icons');
const iconsMeta = JSON.parse(await readFile(join(iconsDir, 'package.json'), 'utf8'));
const sources = [];
const walk = async (dir) => {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) { if (entry.name !== 'vendor') await walk(path); } else if (/\.tsx?$/.test(entry.name)) sources.push(await readFile(path, 'utf8'));
  }
};
await walk(join(root, 'src'));
await walk(join(root, 'frontend'));
const used = new Map();
for (const source of sources) {
  for (const match of source.matchAll(/import\s*\{([^}]+)\}\s*from\s*'react-icons\/(\w+)'/g)) {
    const names = used.get(match[2]) ?? new Set();
    for (const name of match[1].split(',').map((part) => part.trim()).filter(Boolean)) names.add(name);
    used.set(match[2], names);
  }
}
const iconsTarget = join(vendor, 'react-icons');
await mkdir(iconsTarget, { recursive: true });
await copyFile(join(iconsDir, 'LICENSE'), join(iconsTarget, 'LICENSE'));
await writeFile(join(iconsTarget, 'package.json'), `${JSON.stringify({
  name: 'react-icons', version: iconsMeta.version, license: iconsMeta.license, type: 'module', main: 'index.tsx', types: 'index.tsx',
}, null, 2)}\n`);
await writeFile(join(iconsTarget, 'index.tsx'), `// The part of react-icons' IconBase this plugin uses (size, color, title and
// SVG props). Icon data below comes unchanged from react-icons ${iconsMeta.version}.
import { createElement } from 'react';
import type { ReactElement, SVGAttributes } from 'react';

export interface IconTree {
  tag: string;
  attr: Record<string, string>;
  child: IconTree[];
}

export interface IconBaseProps extends SVGAttributes<SVGElement> {
  size?: string | number;
  color?: string;
  title?: string;
}

export type IconType = (props: IconBaseProps) => ReactElement;

const render = (nodes: IconTree[]): ReactElement[] => nodes.map(({ tag, attr, child }, index) => (
  createElement(tag, { key: index, ...attr }, ...render(child))
));

export const GenIcon = (data: IconTree): IconType => ({ size, color, title, style, children, ...props }) => (
  <svg stroke="currentColor" fill="currentColor" strokeWidth="0" {...data.attr} {...props}
    style={{ color, ...style }} height={size ?? '1em'} width={size ?? '1em'} xmlns="http://www.w3.org/2000/svg">
    {title && <title>{title}</title>}
    {render(data.child)}
    {children}
  </svg>
);
`);
for (const [pack, names] of [...used].sort()) {
  const source = await readFile(join(iconsDir, pack, 'index.mjs'), 'utf8');
  const lines = ['// Generated by scripts/vendor.mjs from react-icons; only the icons this plugin uses.', "import { GenIcon } from './index';", ''];
  for (const name of [...names].sort()) {
    const data = source.match(new RegExp(`export function ${name} \\(props\\) \\{\\s*return GenIcon\\((.*?)\\)\\(props\\);`, 's'))?.[1];
    if (!data) throw new Error(`react-icons/${pack}: ${name} not found`);
    lines.push(`export const ${name} = GenIcon(${data});`);
  }
  await writeFile(join(iconsTarget, `${pack}.ts`), `${lines.join('\n')}\n`);
}
readme.push(`| \`react-icons\` (${[...used.values()].reduce((count, names) => count + names.size, 0)} icons) | ${iconsMeta.version} | ${iconsMeta.license} | https://github.com/react-icons/react-icons |`);
readme.push('', 'Heroicons (`hi2`) are MIT; Simple Icons (`si`) are CC0. See `react-icons/LICENSE`.');
await writeFile(join(vendor, 'README.md'), `${readme.join('\n')}\n`);
console.log(`Vendored ${packages.length} packages and react-icons (${[...used].map(([pack, names]) => `${pack}: ${names.size}`).join(', ')}).`);
