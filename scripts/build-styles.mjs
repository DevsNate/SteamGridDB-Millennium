// Compiles upstream's src/styles/style.scss into frontend/generated/upstream-style.ts,
// which is committed so a bare `starlight pack` needs no Sass. Run it after
// changing the SCSS: `node scripts/build-styles.mjs`. With --check it only
// verifies that the committed file is current.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { compile } from 'sass';

const root = new URL('../', import.meta.url);
const target = new URL('frontend/generated/upstream-style.ts', root);
const { css } = compile(fileURLToPath(new URL('src/styles/style.scss', root)), { style: 'expanded' });
const output = [
  '// Generated by scripts/build-styles.mjs from SteamGridDB/decky-steamgriddb src/styles/style.scss; do not edit.',
  `export const upstreamStyle = ${JSON.stringify(css)};`,
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(() => '');
  if (current !== output) {
    console.error('frontend/generated/upstream-style.ts is out of date; run node scripts/build-styles.mjs');
    process.exit(1);
  }
  console.log('Upstream style check passed: committed CSS matches style.scss.');
} else {
  await writeFile(target, output);
  console.log('Wrote frontend/generated/upstream-style.ts');
}
